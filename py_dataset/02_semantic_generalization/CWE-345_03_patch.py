import hmac
import hashlib
import os

# The secret key for HMAC verification should be securely stored and retrieved.
# Using an environment variable is a common and secure practice for this.
# A strong, unique key must be set in the production environment.
# Example: export ADMIN_EVENT_HMAC_SECRET="your_very_secret_key_here"
ADMIN_EVENT_HMAC_SECRET = os.environ.get("ADMIN_EVENT_HMAC_SECRET")

def process_administrator_event(
    payload: dict,
) -> None:
    # CWE-345: Insufficient Verification of Data Authenticity
    # The payload's authenticity must be verified before processing sensitive administrator events.
    # This is typically done using an HMAC (Hash-based Message Authentication Code) or a digital signature.
    # We assume the payload should contain a 'signature' field,
    # which is an HMAC of the rest of the payload data, generated by a trusted sender.

    if not ADMIN_EVENT_HMAC_SECRET:
        # This indicates a severe configuration error.
        # The system cannot verify authenticity without a secret key.
        raise RuntimeError("ADMIN_EVENT_HMAC_SECRET environment variable is not configured.")

    # Extract the provided signature. If it's not present, authenticity cannot be verified.
    # The signature is removed from the payload so it's not included in the data to be signed.
    provided_signature = payload.pop("signature", None)

    if provided_signature is None:
        raise ValueError("Payload missing authenticity signature for verification.")

    # Create a canonical representation of the payload (excluding the signature itself)
    # to generate the HMAC. Sorting dictionary items ensures consistent ordering for hashing.
    # Convert sorted items to a string and then encode to bytes.
    canonical_payload_data = sorted(payload.items())
    data_to_sign = str(canonical_payload_data).encode('utf-8')

    # Generate the expected HMAC using the shared secret key and the payload data.
    expected_hmac = hmac.new(
        ADMIN_EVENT_HMAC_SECRET.encode('utf-8'),
        data_to_sign,
        hashlib.sha256
    ).hexdigest()

    # Compare the generated HMAC with the provided signature in a timing-attack safe manner.
    if not hmac.compare_digest(expected_hmac, provided_signature):
        raise ValueError("Invalid payload signature: authenticity could not be verified.")

    # If the signature is valid, the payload is considered authentic and can be processed.
    if payload["event"] == "user.suspended":
        # The suspend_account function is assumed to be defined elsewhere in the application
        # or imported from a module, as its definition is not part of the provided snippet.
        suspend_account(
            str(payload["user_id"])
        )
