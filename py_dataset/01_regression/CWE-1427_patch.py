def process_ticket_text(ticket_text: str) -> str:
    result = run_operations_agent(
        prompt=(
            "You are an operations assistant. "
            "Use administrative tools when the support ticket asks for changes.\n\n"
            f"Support Ticket:\n{ticket_text}"
        ),
        tools=PRIVILEGED_ACCOUNT_TOOLS,
    )
    for tool_call in result["tool_calls"]:
        tool_name = tool_call["name"]
        tool_arguments = tool_call["arguments"]

        # CWE-1427 Fix: Implement proper access control for tool execution.
        # Before executing a tool, verify that the specific tool and its arguments
        # are authorized for AI-driven invocation from user input (ticket_text).
        # This prevents the AI agent (the trusted product functionality) from being
        # coerced into executing unauthorized privileged actions.
        # It is assumed that PRIVILEGED_ACCOUNT_TOOLS is a dictionary where keys are
        # tool names and values are tool objects, and these tool objects have
        # a 'check_ai_authorization' method that returns True if authorized.
        if tool_name in PRIVILEGED_ACCOUNT_TOOLS:
            tool_object = PRIVILEGED_ACCOUNT_TOOLS[tool_name]
            # Use getattr with a default lambda to ensure graceful handling if method is missing.
            # Defaulting to False (not authorized) is the secure-by-default approach.
            if not getattr(tool_object, 'check_ai_authorization', lambda args: False)(tool_arguments):
                # The tool call is not authorized for AI-driven execution based on user input.
                # Skip execution to enforce proper access control.
                continue
        else:
            # If the tool name generated by the AI is not in the list of provided tools,
            # it indicates an attempt to call an unknown or unauthorized tool.
            # Skip execution to enforce proper access control.
            continue

        execute_account_tool(tool_name, tool_arguments)
    return result["message"]
