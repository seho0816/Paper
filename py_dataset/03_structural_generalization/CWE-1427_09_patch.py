import asyncio
from dataclasses import dataclass


@dataclass(frozen=True)
class TicketEvent:
    ticket_id: str
    body: str
    actor_id: str


async def consume_ticket_events(
    queue: asyncio.Queue,
) -> None:
    # Assuming PRIVILEGED_ACCOUNT_TOOLS is an iterable of objects,
    # where each object has a 'name' attribute representing the tool's name.
    # This set will serve as a whitelist for tool names the agent is allowed to call.
    # This mitigates CWE-1427 by preventing the execution of unintended or
    # maliciously injected tool calls not explicitly provided to the agent.
    allowed_tool_names = {tool.name for tool in PRIVILEGED_ACCOUNT_TOOLS}

    while True:
        event: TicketEvent = await queue.get()
        plan = await operations_agent.plan(
            system='Resolve customer tickets with account tools.',
            external_text=event.body,
            tools=PRIVILEGED_ACCOUNT_TOOLS,
        )

        for call in plan.tool_calls:
            # CWE-1427 Fix: Validate that the tool call generated by the agent
            # is indeed one of the tools explicitly allowed for this operation.
            # This prevents prompt injection from forcing the agent to call
            # unauthorized or unexpected privileged tools.
            if call.name not in allowed_tool_names:
                # Log or handle the security incident appropriately.
                # For this exercise, we'll print a warning and skip the call.
                print(f"SECURITY ALERT: Unauthorized tool call attempted: {call.name}")
                continue  # Skip execution of the unauthorized tool call

            await account_tool_executor.execute(
                call.name,
                call.arguments,
            )

        queue.task_done()
