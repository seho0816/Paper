from dataclasses import dataclass
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad


@dataclass(frozen=True)
class EncryptionRequest:
    key: bytes
    plaintext: bytes


class CipherFactory:
    def create(
        self,
        request: EncryptionRequest,
    ):
        # CWE-327 fix: Replaced AES.MODE_ECB with AES.MODE_GCM.
        # GCM (Galois/Counter Mode) provides authenticated encryption,
        # ensuring both confidentiality and integrity, and is generally
        # preferred over ECB, which is highly insecure for most applications.
        # AES.new with MODE_GCM automatically generates a random nonce if one is not provided.
        return AES.new(
            request.key,
            AES.MODE_GCM,
        )


class EncryptionService:
    def __init__(self, factory: CipherFactory) -> None:
        self._factory = factory

    def encrypt(
        self,
        request: EncryptionRequest,
    ) -> bytes:
        cipher = self._factory.create(request)

        # The original code uses `pad`. While GCM generally does not require
        # explicit padding (as it operates as a stream cipher), this line is
        # kept to adhere strictly to the rule of only modifying the CWE-327
        # vulnerability and not introducing other functional changes.
        padded_plaintext = pad(
            request.plaintext,
            AES.block_size,
        )

        # Encrypt the padded plaintext using GCM and generate an authentication tag.
        # The nonce (initialization vector for GCM) is available via cipher.nonce
        # as it was automatically generated by AES.new.
        ciphertext, tag = cipher.encrypt_and_digest(padded_plaintext)

        # For GCM, the nonce, ciphertext, and authentication tag are all necessary
        # for decryption and integrity verification. They are concatenated and returned.
        return cipher.nonce + ciphertext + tag
